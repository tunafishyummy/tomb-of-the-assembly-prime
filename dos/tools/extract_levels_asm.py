#!/usr/bin/env python3
"""Extract the five campaign levels from tomb_of_mask.asm into src/levels.inc (assembly data).
Usage: python3 tools/extract_levels_asm.py ../Simulador/tomb_of_mask.asm src/levels.inc"""
import re, sys
asm = open(sys.argv[1], encoding='utf-8', errors='replace').read().replace('\r', '')
def num(name): return int(re.search(r'static %s \+ #0, #(\d+)' % name, asm).group(1))
out = ['# generated by tools/extract_levels_asm.py - do not edit',
       '    .equ NUM_LEVELS, 5', '    .equ LEVEL_W, 40', '    .equ LEVEL_H, 28', '    .text', '# 28 rows of 40 tiles per level (the ICMC HUD rows are dropped)', 'level_data:']
for i in range(1, 6):
    s = re.search(r'^level%d : string "(.*)"\s*$' % i, asm, re.M).group(1)
    assert len(s) == 1200 and '"' not in s and '\\' not in s
    out.append('    # level %d' % i)
    for r in range(28): out.append('    .ascii "%s"' % s[r*40:(r+1)*40])
flips = {3: 1046, 4: 1046, 5: 85}
out.append('level_start:  .word ' + ','.join(str(num('start%d' % i)) for i in range(1, 6)))
out.append('level_exit:   .word ' + ','.join(str(num('exit%d' % i)) for i in range(1, 6)))
out.append('level_flip:   .word ' + ','.join(str(flips.get(i, 0)) for i in range(1, 6)))
open(sys.argv[2], 'w').write('\n'.join(out) + '\n')
