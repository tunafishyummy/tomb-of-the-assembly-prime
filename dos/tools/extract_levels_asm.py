#!/usr/bin/env python3
"""Extract the five campaign maps into the DOS assembly and C reference data.

Usage: python3 tools/extract_levels_asm.py ../Simulador/tomb_of_mask.asm \
       src/levels.inc reference_c/src/levels.h
"""
import re
import sys

asm_path, asm_output, c_output = sys.argv[1:4]
with open(asm_path, encoding="utf-8", errors="replace") as source:
    asm = source.read().replace("\r", "")


def num(name):
    match = re.search(r"static %s \+ #0, #(\d+)" % name, asm)
    if not match:
        raise ValueError("missing map metadata: %s" % name)
    return int(match.group(1))


levels = []
for i in range(1, 6):
    match = re.search(r'^level%d : string "(.*)"\s*$' % i, asm, re.M)
    if not match:
        raise ValueError("missing level%d map" % i)
    level = match.group(1)
    if len(level) != 1200 or '"' in level or "\\" in level:
        raise ValueError("level%d must be a 1200-character map string" % i)
    levels.append(level[:40 * 28])

starts = [num("start%d" % i) for i in range(1, 6)]
exits = [num("exit%d" % i) for i in range(1, 6)]
flips = [num("flip%d" % i) for i in range(1, 6)]
for i, level in enumerate(levels):
    if not 0 <= starts[i] < 40 * 28 or level[starts[i]] != " ":
        raise ValueError("level%d start must point to a floor tile" % (i + 1))
    if not 0 <= exits[i] < 40 * 28 or level[exits[i]] != " ":
        raise ValueError("level%d exit must point to a floor tile" % (i + 1))

assembly = [
    "# generated by tools/extract_levels_asm.py - do not edit",
    "    .equ NUM_LEVELS, 5",
    "    .equ LEVEL_W, 40",
    "    .equ LEVEL_H, 28",
    "    .text",
    "# 28 rows of 40 tiles per level (the ICMC HUD rows are dropped)",
    "level_data:",
]
for i, level in enumerate(levels, 1):
    assembly.append("    # level %d" % i)
    for row in range(28):
        assembly.append('    .ascii "%s"' % level[row * 40:(row + 1) * 40])
assembly.extend([
    "level_start:  .word " + ",".join(map(str, starts)),
    "level_exit:   .word " + ",".join(map(str, exits)),
    "level_flip:   .word " + ",".join(map(str, flips)),
])
with open(asm_output, "w", encoding="utf-8", newline="\n") as output:
    output.write("\n".join(assembly) + "\n")

c_header = [
    "/* generated by tools/extract_levels_asm.py - do not edit */",
    "#define LEVEL_COUNT 5",
    "#define LEVEL_W 40",
    "#define LEVEL_H 28",
    "static const char level_data[LEVEL_COUNT][LEVEL_W*LEVEL_H+1] = {",
]
c_header.extend('  "%s"%s' % (level, "," if i < 4 else "")
                for i, level in enumerate(levels))
c_header.extend([
    "};",
    "static const short level_start[LEVEL_COUNT] = {%s};" % ",".join(map(str, starts)),
    "static const short level_exit[LEVEL_COUNT] = {%s};" % ",".join(map(str, exits)),
    "static const short level_flip[LEVEL_COUNT] = {%s};" % ",".join(map(str, flips)),
])
with open(c_output, "w", encoding="utf-8", newline="\n") as output:
    output.write("\n".join(c_header) + "\n")
