#!/usr/bin/env python3
"""Compile editable campaign grids into the simulator, DOS assembly, and C data.

Usage: python3 tools/extract_levels_asm.py campaign_maps.txt \
       ../Simulador/tomb_of_mask.asm src/levels.inc reference_c/src/levels.h
"""
import re
import sys

map_path, simulator_path, asm_output, c_output = sys.argv[1:5]
with open(map_path, encoding="utf-8") as source:
    map_source = source.read().replace("\r", "")
with open(simulator_path, encoding="utf-8", errors="replace") as source:
    simulator = source.read().replace("\r", "")


def editable_maps(source):
    maps = {}
    lines = source.splitlines()
    index = 0
    while index < len(lines):
        begin = re.fullmatch(r"MAP ([1-5])", lines[index])
        if not begin:
            index += 1
            continue

        level_number = int(begin.group(1))
        if level_number in maps:
            raise ValueError("duplicate editable map %d" % level_number)
        index += 1
        rows = lines[index:index + 28]
        if len(rows) != 28:
            raise ValueError("map%d must contain exactly 28 rows" % level_number)
        if any(len(row) != 40 for row in rows):
            raise ValueError("every map%d row must contain exactly 40 tiles" % level_number)
        maps[level_number] = rows
        index += 28

    if set(maps) != set(range(1, 6)):
        raise ValueError("editable map blocks 1 through 5 are required")
    return maps


tile_map = {"#": "}", ".": " ", "C": "#", "S": " ", "E": " "}
game_tiles = set("}{*$=@%<&^|!")
maps = editable_maps(map_source)
levels = []
starts = []
exits = []
for i in range(1, 6):
    cells = []
    start = None
    exit_cell = None
    for y, row in enumerate(maps[i]):
        for x, tile in enumerate(row):
            if tile == "S":
                if start is not None:
                    raise ValueError("map%d must contain exactly one S start" % i)
                start = y * 40 + x
            elif tile == "E":
                if exit_cell is not None:
                    raise ValueError("map%d must contain exactly one E exit" % i)
                exit_cell = y * 40 + x
            elif tile not in tile_map and tile not in game_tiles:
                raise ValueError("map%d contains unsupported tile %r at (%d,%d)" %
                                 (i, tile, x, y))
            cells.append(tile_map.get(tile, tile))
    if start is None or exit_cell is None:
        raise ValueError("map%d must contain exactly one S start and one E exit" % i)
    starts.append(start)
    exits.append(exit_cell)
    levels.append("".join(cells))

flips = []
for i in range(1, 6):
    match = re.search(r"static flip%d \+ #0, #(\d+)" % i, simulator)
    if not match:
        raise ValueError("missing map metadata: flip%d" % i)
    flips.append(int(match.group(1)))

updated_simulator = simulator
for i, level in enumerate(levels, 1):
    match = re.search(r'^level%d : string "(.*)"\s*$' % i, updated_simulator, re.M)
    if not match or len(match.group(1)) != 1200:
        raise ValueError("level%d must have an existing 1200-character string" % i)
    encoded = level + match.group(1)[1120:]
    updated_simulator = re.sub(
        r'^level%d : string ".*"\s*$' % i,
        'level%d : string "%s"' % (i, encoded),
        updated_simulator,
        count=1,
        flags=re.M,
    )
    updated_simulator, start_count = re.subn(
        r"(static start%d \+ #0, #)\d+" % i,
        r"\g<1>%d" % starts[i - 1],
        updated_simulator,
        count=1,
    )
    updated_simulator, exit_count = re.subn(
        r"(static exit%d \+ #0, #)\d+(?:\s*;.*)?$" % i,
        r"\g<1>%d ; (%d,%d) opening in the outer wall" %
        (exits[i - 1], exits[i - 1] % 40, exits[i - 1] // 40),
        updated_simulator,
        count=1,
        flags=re.M,
    )
    if start_count != 1 or exit_count != 1:
        raise ValueError("missing start/exit metadata for map%d" % i)

for i, level in enumerate(levels):
    if level[starts[i]] != " " or level[exits[i]] != " ":
        raise ValueError("map%d start and exit markers must map to floor" % (i + 1))

assembly = [
    "# generated by tools/extract_levels_asm.py - do not edit",
    "    .equ NUM_LEVELS, 5",
    "    .equ LEVEL_W, 40",
    "    .equ LEVEL_H, 28",
    "    .text",
    "# 28 rows of 40 tiles per level (the ICMC HUD rows are dropped)",
    "level_data:",
]
for i, level in enumerate(levels, 1):
    assembly.append("    # level %d" % i)
    for row in range(28):
        assembly.append('    .ascii "%s"' % level[row * 40:(row + 1) * 40])
assembly.extend([
    "level_start:  .word " + ",".join(map(str, starts)),
    "level_exit:   .word " + ",".join(map(str, exits)),
    "level_flip:   .word " + ",".join(map(str, flips)),
])
with open(asm_output, "w", encoding="utf-8", newline="\n") as output:
    output.write("\n".join(assembly) + "\n")

c_header = [
    "/* generated by tools/extract_levels_asm.py - do not edit */",
    "#define LEVEL_COUNT 5",
    "#define LEVEL_W 40",
    "#define LEVEL_H 28",
    "static const char level_data[LEVEL_COUNT][LEVEL_W*LEVEL_H+1] = {",
]
c_header.extend('  "%s"%s' % (level, "," if i < 4 else "")
                for i, level in enumerate(levels))
c_header.extend([
    "};",
    "static const short level_start[LEVEL_COUNT] = {%s};" % ",".join(map(str, starts)),
    "static const short level_exit[LEVEL_COUNT] = {%s};" % ",".join(map(str, exits)),
    "static const short level_flip[LEVEL_COUNT] = {%s};" % ",".join(map(str, flips)),
])
with open(c_output, "w", encoding="utf-8", newline="\n") as output:
    output.write("\n".join(c_header) + "\n")

with open(simulator_path, "w", encoding="utf-8", newline="\n") as source:
    source.write(updated_simulator)
